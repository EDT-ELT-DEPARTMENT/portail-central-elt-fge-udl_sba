-- PORTAIL CENTRAL ELT — schéma initial Supabase
-- À exécuter une seule fois dans Supabase > SQL Editor.
-- Ne supprime et ne modifie aucune table métier existante.

create extension if not exists pgcrypto;

create table if not exists public.portal_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text not null unique,
    full_name text not null default '',
    role text not null default 'etudiant'
        check (role in ('admin','personnel','enseignant','etudiant')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.portal_app_access (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.portal_profiles(id) on delete cascade,
    app_key text not null check (app_key in ('edt','hsup','stages')),
    enabled boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(user_id, app_key)
);

create table if not exists public.portal_sso_codes (
    id bigint generated by default as identity primary key,
    code_hash text not null unique,
    user_id uuid not null references public.portal_profiles(id) on delete cascade,
    app_key text not null check (app_key in ('edt','hsup','stages')),
    expires_at timestamptz not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_portal_sso_codes_expiry
    on public.portal_sso_codes(expires_at);

create table if not exists public.portal_audit_logs (
    id bigint generated by default as identity primary key,
    user_id uuid references public.portal_profiles(id) on delete set null,
    app_key text,
    event_type text not null,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

-- Crée automatiquement le profil central après inscription Supabase Auth.
create or replace function public.portal_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.portal_profiles(id, email, full_name, role, is_active)
    values (
        new.id,
        coalesce(new.email, ''),
        coalesce(new.raw_user_meta_data->>'full_name', ''),
        'etudiant',
        true
    )
    on conflict (id) do update
      set email = excluded.email;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created_portal on auth.users;
create trigger on_auth_user_created_portal
after insert on auth.users
for each row execute procedure public.portal_handle_new_user();

-- Récupère aussi les comptes Supabase Auth déjà existants (notamment H.SUP).
-- Ils reçoivent un profil central sans autorisation applicative automatique.
insert into public.portal_profiles(id, email, full_name, role, is_active)
select
    u.id,
    coalesce(u.email, ''),
    coalesce(u.raw_user_meta_data->>'full_name', ''),
    'etudiant',
    true
from auth.users u
where coalesce(u.email, '') <> ''
on conflict (id) do nothing;

-- Fonction sécurisée utilisée par les politiques RLS sans récursion.
create or replace function public.portal_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.portal_profiles p
        where p.id = auth.uid()
          and p.role = 'admin'
          and p.is_active = true
    );
$$;

alter table public.portal_profiles enable row level security;
alter table public.portal_app_access enable row level security;
alter table public.portal_sso_codes enable row level security;
alter table public.portal_audit_logs enable row level security;

drop policy if exists portal_profiles_read_self_or_admin on public.portal_profiles;
create policy portal_profiles_read_self_or_admin
on public.portal_profiles for select to authenticated
using (id = auth.uid() or public.portal_is_admin());

drop policy if exists portal_access_read_self_or_admin on public.portal_app_access;
create policy portal_access_read_self_or_admin
on public.portal_app_access for select to authenticated
using (user_id = auth.uid() or public.portal_is_admin());

drop policy if exists portal_audit_admin_read on public.portal_audit_logs;
create policy portal_audit_admin_read
on public.portal_audit_logs for select to authenticated
using (public.portal_is_admin());

-- Aucun accès direct aux codes SSO depuis les navigateurs/utilisateurs.
revoke all on public.portal_sso_codes from anon, authenticated;
revoke all on public.portal_audit_logs from anon, authenticated;
revoke insert, update, delete on public.portal_profiles from anon, authenticated;
revoke insert, update, delete on public.portal_app_access from anon, authenticated;

grant select on public.portal_profiles to authenticated;
grant select on public.portal_app_access to authenticated;
grant select on public.portal_audit_logs to authenticated;
grant execute on function public.portal_is_admin() to authenticated;

-- Émission d'un code aléatoire, à usage unique, valable 90 secondes.
create or replace function public.portal_issue_sso_code(
    p_user_id uuid,
    p_app_key text
)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_code text;
begin
    if p_app_key not in ('edt','hsup','stages') then
        raise exception 'Application inconnue';
    end if;

    if not exists (
        select 1 from public.portal_profiles p
        join public.portal_app_access a on a.user_id = p.id
        where p.id = p_user_id
          and p.is_active = true
          and a.app_key = p_app_key
          and a.enabled = true
    ) then
        raise exception 'Compte inactif ou accès non autorisé';
    end if;

    v_code := encode(gen_random_bytes(32), 'hex');

    insert into public.portal_sso_codes(code_hash, user_id, app_key, expires_at)
    values (
        encode(digest(v_code, 'sha256'), 'hex'),
        p_user_id,
        p_app_key,
        now() + interval '90 seconds'
    );

    insert into public.portal_audit_logs(user_id, app_key, event_type)
    values (p_user_id, p_app_key, 'sso_code_issued');

    return v_code;
end;
$$;

-- Consommation atomique : un code ne peut réussir qu'une seule fois.
create or replace function public.portal_consume_sso_code(
    p_code text,
    p_app_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_user_id uuid;
    v_result jsonb;
begin
    if coalesce(p_code, '') = '' or p_app_key not in ('edt','hsup','stages') then
        return null;
    end if;

    delete from public.portal_sso_codes c
    where c.code_hash = encode(digest(p_code, 'sha256'), 'hex')
      and c.app_key = p_app_key
      and c.expires_at > now()
    returning c.user_id into v_user_id;

    if v_user_id is null then
        return null;
    end if;

    select jsonb_build_object(
        'user_id', p.id,
        'email', p.email,
        'full_name', p.full_name,
        'role', p.role,
        'app_key', p_app_key
    )
    into v_result
    from public.portal_profiles p
    join public.portal_app_access a
      on a.user_id = p.id
     and a.app_key = p_app_key
     and a.enabled = true
    where p.id = v_user_id
      and p.is_active = true;

    if v_result is null then
        return null;
    end if;

    insert into public.portal_audit_logs(user_id, app_key, event_type)
    values (v_user_id, p_app_key, 'sso_code_consumed');

    return v_result;
end;
$$;

-- Les RPC SSO sont réservées à service_role (jamais aux navigateurs).
revoke all on function public.portal_issue_sso_code(uuid, text) from public, anon, authenticated;
revoke all on function public.portal_consume_sso_code(text, text) from public, anon, authenticated;
grant execute on function public.portal_issue_sso_code(uuid, text) to service_role;
grant execute on function public.portal_consume_sso_code(text, text) to service_role;

